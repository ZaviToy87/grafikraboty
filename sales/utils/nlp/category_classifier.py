from typing import List, Tuple, Optional
import re

class CategoryClassifier:
    """
    Простой классификатор категорий по ключевым словам.
    Можно расширить через JSON-словарь или ML модель позже.
    """
    CATEGORIES = [
        ("корм", "Корм"),
        ("пауч", "Корм"),
        ("консервы", "Корм"),
        ("лакомство", "Лакомства"),
        ("снек", "Лакомства"),
        ("жевательный", "Лакомства"),
        ("игрушка", "Игрушки"),
        ("ошейник", "Аксессуары"),
        ("когтерез", "Аксессуары"),
        ("наполнитель", "Наполнители"),
        ("пеленки", "Гигиена"),
        ("шампунь", "Гигиена"),
        ("таблетки", "Медицина"),
        ("капли", "Медицина"),
        ("витамины", "Медицина"),
        ("сухой", "Корм"),
        ("влажный", "Корм"),
        ("для кошек", "Корм для кошек"),
        ("для собак", "Корм для собак"),
        ("для котят", "Корм для котят"),
        ("стерилизованные", "Корм для стерилизованных"),
        ("чувствительное пищеварение", "Корм для чувствительного ЖКТ"),
        ("урин", "Корм для мочевыводящих путей"),
        ("гастро", "Корм для ЖКТ"),
    ]

    @classmethod
    def classify(cls, product_name: str) -> str:
        product_lower = product_name.lower()
        for keyword, category in cls.CATEGORIES:
            if keyword in product_lower:
                return category
        return "Прочее"